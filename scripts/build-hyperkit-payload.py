"""Build the position-independent HyperKit payload and describe its entry points."""

from pathlib import Path
import struct
import subprocess


ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
BUILD.mkdir(exist_ok=True)


def run(arguments):
    return subprocess.check_output(arguments, cwd=ROOT, stderr=subprocess.STDOUT)


try:
    sdk_version = run(["xcrun", "--sdk", "macosx", "--show-sdk-version"]).decode().strip()
    run([
        "xcrun", "clang", "-arch", "x86_64", "-mmacosx-version-min=10.15",
        "-Oz", "-fPIC", "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
        "-fvisibility=hidden", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
        "-mno-red-zone", "-DRHV_EMBEDDED", "-Wall", "-Wextra", "-Werror",
        "-c", "compat/HyperKitCompat.c", "-o", "build/HyperKitPayload.o",
    ])
    run([
        "xcrun", "ld", "-arch", "x86_64", "-static", "-no_pie", "-no_uuid",
        "-e", "_rhv_compat_open", "-platform_version", "macos", "10.15", sdk_version,
        "build/HyperKitPayload.o", "-o", "build/HyperKitPayload",
    ])
except subprocess.CalledProcessError as error:
    print(error.output.decode(errors="replace"))
    raise

image = (BUILD / "HyperKitPayload").read_bytes()
magic, cpu, _, _, commands, command_bytes, _, _ = struct.unpack_from("<8I", image)
assert magic == 0xFEEDFACF and cpu == 0x01000007
segments = []
cursor = 32
for _ in range(commands):
    kind, size = struct.unpack_from("<II", image, cursor)
    assert size >= 8 and cursor + size <= 32 + command_bytes
    if kind == 0x19:
        name, address, memory_size, offset, file_size = struct.unpack_from("<16s4Q", image, cursor + 8)
        name = name.rstrip(b"\0")
        if name not in (b"__PAGEZERO", b"__LINKEDIT"):
            segments.append((name, address, memory_size, offset, file_size))
    if kind in (0x22, 0x80000022):
        assert struct.unpack_from("<I", image, cursor + 12)[0] == 0, "payload needs rebasing"
    if kind == 0x80000034:
        assert struct.unpack_from("<I", image, cursor + 12)[0] == 0, "payload has chained fixups"
    cursor += size
assert cursor == 32 + command_bytes
assert not run(["xcrun", "nm", "-u", "build/HyperKitPayload"]).strip(), "payload imports external symbols"

text = next(segment for segment in segments if segment[0] == b"__TEXT")
data = next(segment for segment in segments if segment[0] == b"__DATA")
base = text[1]
assert data[1] > base and data[1] % 4096 == 0
size = max(address + memory_size for _, address, memory_size, _, _ in segments) - base
assert 0 < size <= 65536
payload = bytearray(size)
for _, address, memory_size, offset, file_size in segments:
    assert address >= base and file_size <= memory_size and offset + file_size <= len(image)
    start = address - base
    payload[start:start + file_size] = image[offset:offset + file_size]

symbols = {}
for line in run(["xcrun", "nm", "-n", "build/HyperKitPayload"]).decode().splitlines():
    parts = line.split()
    if len(parts) == 3:
        symbols[parts[2]] = int(parts[0], 16) - base
entries = {
    "config": symbols["_rhv_compat_config"],
    "open": symbols["_rhv_compat_open"],
    "connect": symbols["_rhv_compat_connect"],
}
assert data[1] - base <= entries["config"] <= size - 48
assert all(0 < entries[name] < data[1] - base for name in ("open", "connect"))
assert struct.unpack_from("<Q", payload, entries["config"])[0] == 0x524856434F4D5031
lines = [
    "/* Generated by scripts/build-hyperkit-payload.py. */",
    "#ifndef RHV_HYPERKIT_PAYLOAD_H",
    "#define RHV_HYPERKIT_PAYLOAD_H",
    "#include <stdint.h>",
    f"static const uint64_t rhv_payload_size = {size};",
    f"static const uint64_t rhv_payload_text_size = {data[1] - base};",
]
for name, offset in entries.items():
    lines.append(f"static const uint64_t rhv_payload_{name}_offset = {offset};")
lines.append("static const unsigned char rhv_payload_bytes[] = {")
for offset in range(0, len(payload), 20):
    lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in payload[offset:offset + 20]) + ",")
lines.extend(["};", "#endif", ""])
(BUILD / "HyperKitPayload.h").write_text("\n".join(lines))
(BUILD / "HyperKitPayload.bin").write_bytes(payload)
print(f"HyperKit payload: {size} bytes, text {data[1] - base}, entries {entries}")
